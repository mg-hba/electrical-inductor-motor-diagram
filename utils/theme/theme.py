    # ============================================================
    # ================== CONFIG SYNC =============================
    # ============================================================
    @staticmethod
    def refresh_from_config(json_manager):
        """
        Refresh theme from config.json (if user customized).
        """
        try:
            config = json_manager.config.get('window_settings', {})
            if 'main_bg_color' in config:
                Theme.MAIN_BG = tuple(config['main_bg_color'])
            if 'header_bg_color' in config:
                Theme.HEADER_BG = tuple(config['header_bg_color'])
            if 'error_bg_color' in config:
                Theme.INPUT_ERROR_BG = tuple(config['error_bg_color'])
        except Exception:
            pass
